"""Static landing-page regression checks using only the Python standard library."""
import json
import re
import unittest
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'param', 'source', 'track', 'wbr'}


class Page(HTMLParser):
    def __init__(self, text):
        super().__init__()
        self.nodes = []
        self.stack = []
        self.errors = []
        self.ancestors = []
        self.open_nodes = []
        self.text = []
        self.feed(text)

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        self.ancestors.append(tuple(self.open_nodes))
        self.nodes.append((tag, attrs))
        if tag not in VOID:
            self.stack.append(tag)
            self.open_nodes.append(len(self.nodes) - 1)

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        if not self.stack or self.stack[-1] != tag:
            self.errors.append((tag, self.stack[-3:]))
        else:
            self.stack.pop()
            self.open_nodes.pop()

    def handle_data(self, text):
        self.text.append(text)


class LandingIntegrity(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.raw = (ROOT / 'index.html').read_text()
        cls.page = Page(cls.raw)

    def test_structure_and_sections(self):
        self.assertEqual(self.page.errors, [])
        self.assertEqual(self.page.stack, [])
        ids = [a['id'] for _, a in self.page.nodes if 'id' in a]
        self.assertEqual(len(ids), len(set(ids)))
        self.assertEqual(sum(t == 'main' for t, _ in self.page.nodes), 1)
        sections = [a.get('id') for t, a in self.page.nodes if t == 'section']
        self.assertEqual(sections, ['home', 'media', 'about', 'ethos', 'packages', 'location', 'testimonials', 'gallery', 'clinic-reels', 'care-cta'])

    def test_media_is_inside_hero_wrapper_after_hero(self):
        nodes = self.page.nodes
        wrapper = next(i for i, (_, a) in enumerate(nodes) if a.get('class') == 'hero-wrap')
        hero = next(i for i, (_, a) in enumerate(nodes) if a.get('id') == 'home')
        media = next(i for i, (_, a) in enumerate(nodes) if a.get('id') == 'media')
        self.assertIn(wrapper, self.page.ancestors[hero])
        self.assertEqual(self.page.ancestors[hero], self.page.ancestors[media])
        self.assertLess(hero, media)
        children = [i for i, ancestors in enumerate(self.page.ancestors) if ancestors and ancestors[-1] == wrapper]
        self.assertEqual(children, [hero, media])

    def test_three_unique_usp_items(self):
        items = [a for _, a in self.page.nodes if a.get('class') == 'usp-item']
        groups = [a for _, a in self.page.nodes if a.get('class') == 'logo-group']
        self.assertEqual(len(items), 3)
        self.assertEqual(len(groups), 1)
        self.assertNotIn('aria-hidden', groups[0])

    def test_assets_and_local_targets(self):
        ids = {a['id'] for _, a in self.page.nodes if 'id' in a}
        for tag, attrs in self.page.nodes:
            if tag not in {'a', 'link', 'img', 'script', 'textpath'}:
                continue
            url = attrs.get('src') or attrs.get('href', '')
            if url.startswith('#'):
                self.assertIn(url[1:], ids)
            elif url in ('services/', 'about/'):
                # Route is generated by Eleventy; built destinations are checked by the build smoke test.
                self.assertTrue((ROOT / ('blog/' + url.rstrip('/') + '.11ty.js')).is_file())
            elif url and not url.startswith(('https:', 'http:', 'data:', 'tel:', 'mailto:')):
                self.assertTrue((ROOT / url).exists(), url)
        for asset in re.findall(r'url\(([^)]+)\)', self.raw):
            self.assertTrue((ROOT / asset.strip('"\'')).exists(), asset)

    def test_original_treatments_and_quote(self):
        content = json.loads((ROOT / 'tests/fixtures/treatments.json').read_text())
        text = ' '.join(' '.join(self.page.text).split())
        # Preserve service coverage while allowing the reviewed plain-language labels.
        patient_labels = {
            'Advanced Liposuction': 'Liposuction',
            'Bespoke Augmentation': 'Breast Augmentation',
            'Proportional Reduction': 'Breast Reduction',
            'Reshaping &amp; Lift': 'Breast Reshaping &amp; Lift',
            'Lump Excision': 'Breast Lump Removal',
            'Follicular Transplant': 'Hair Transplant',
            'Head &amp; Neck Cancer Recon': 'Head &amp; Neck Cancer Reconstruction',
            'Advanced Wound Management': 'Wound Assessment &amp; Care',
            'Diabetic Foot Salvage': 'Diabetic Foot Care',
        }
        for item in content['treatments']:
            self.assertIn(patient_labels.get(item, item).replace('&amp;', '&'), text)
        quote = content['philosophy']
        self.assertIn(' '.join(quote.split()), text)
        self.assertEqual(sum(t == 'dialog' and a.get('class') == 'treatment-dialog' for t, a in self.page.nodes), 8)
        fallback = re.search(r'<noscript>(.*?)</noscript>', self.raw, re.S).group(1)
        self.assertEqual(len(re.findall(r'<details>', fallback)), 8)

    def test_optimized_assets_and_hero(self):
        hero = next(a for t, a in self.page.nodes if t == 'img' and a.get('class') == 'hero-slide')
        self.assertEqual(hero['src'], 'assets/images/hero.webp')
        self.assertEqual(hero['fetchpriority'], 'high')
        for file in (ROOT / 'assets/images').rglob('*.webp'):
            data = file.read_bytes()
            self.assertEqual(data[:4], b'RIFF', str(file))
            self.assertEqual(data[8:12], b'WEBP', str(file))
        self.assertEqual((ROOT / 'assets/images/hero.webp').read_bytes()[8:12], b'WEBP')
        self.assertNotIn('@import', (ROOT / 'assets/css/base.css').read_text())
        self.assertFalse((ROOT / 'archive').exists())
        self.assertFalse(any((ROOT / 'assets/vendor').glob('*swiper*')))

    def test_reference_branding_is_absent_from_first_party_site_code(self):
        files = [ROOT / 'index.html', ROOT / 'lib/blog.cjs',
                 ROOT / 'assets/js/main.js', ROOT / 'assets/js/blog.js',
                 *(ROOT / 'assets/css').glob('*.css'),
                 *(ROOT / 'blog/_includes').glob('*.html')]
        for file in files:
            self.assertNotRegex(file.read_text().lower(),
                                r'maisonabelane|ma-web|--ma-|(?:bg|text)-ma-|dantha-gudi', str(file))
        for folder in ['assets/css', 'assets/js', 'assets/images', 'assets/fonts', 'assets/vendor']:
            self.assertTrue((ROOT / folder).is_dir(), folder)
        self.assertFalse(list(ROOT.glob('*.css')))
        self.assertFalse(list(ROOT.glob('*.js')))

    def test_expertise_capsules_and_dialog_targets(self):
        nodes = self.page.nodes
        section = next(i for i, (_, a) in enumerate(nodes) if a.get('id') == 'packages')
        cards = [(i, a) for i, (tag, a) in enumerate(nodes) if tag == 'article' and a.get('class') == 'expertise-card']
        self.assertEqual([a['id'] for _, a in cards], [f'service-{i}' for i in range(1, 9)])
        for number, (index, _) in enumerate(cards, 1):
            self.assertIn(section, self.page.ancestors[index])
            descendants = [(tag, a) for i, (tag, a) in enumerate(nodes) if index in self.page.ancestors[i]]
            self.assertEqual(sum(tag == 'h3' for tag, _ in descendants), 1)
            self.assertEqual(sum(tag == 'img' for tag, _ in descendants), 1)
            self.assertEqual(sum(a.get('class') == 'expertise-label' for _, a in descendants), 1)
            button = next(a for tag, a in descendants if tag == 'button')
            self.assertEqual(button['data-dialog'], f'treatment-{number}')
            self.assertEqual(button['class'], 'expertise-trigger')
            for ancestor in self.page.ancestors[index]:
                self.assertNotIn('hidden', nodes[ancestor][1])
        section_nodes = [a for i, (_, a) in enumerate(nodes) if section in self.page.ancestors[i]]
        self.assertFalse(any('swiper' in a.get('class', '') for a in section_nodes))
        self.assertFalse(any('custom-prev' in a.get('class', '') or 'custom-next' in a.get('class', '') for a in section_nodes))
        source = (ROOT / 'assets/js/main.js').read_text()
        self.assertNotIn('services-swiper', source)
        self.assertNotIn("new Swiper(", source)

    def test_accessibility_targets(self):
        ids = {a['id'] for _, a in self.page.nodes if 'id' in a}
        for tag, attrs in self.page.nodes:
            for field in ['aria-controls', 'aria-labelledby']:
                for target in attrs.get(field, '').split():
                    self.assertIn(target, ids)
            if tag == 'input':
                self.assertTrue(attrs.get('aria-label'))
            if tag == 'button':
                self.assertEqual(attrs.get('type'), 'button')
            if tag == 'a' and attrs.get('target') == '_blank':
                self.assertIn('noopener', attrs.get('rel', ''))

    def test_closing_section_is_isolated_and_links_to_booking(self):
        nodes = self.page.nodes
        section = next(i for i, (_, a) in enumerate(nodes) if a.get('id') == 'care-cta')
        footer = next(i for i, (tag, _) in enumerate(nodes) if tag == 'footer')
        main = next(i for i, (tag, _) in enumerate(nodes) if tag == 'main')
        self.assertIn(main, self.page.ancestors[section])
        self.assertLess(section, footer)
        descendants = [(tag, a) for i, (tag, a) in enumerate(nodes) if section in self.page.ancestors[i]]
        canvas = [a for tag, a in descendants if tag == 'canvas']
        self.assertEqual(len(canvas), 1)
        self.assertIn('hidden', canvas[0])
        booking = [a for tag, a in descendants if tag == 'a']
        self.assertEqual(len(booking), 1)
        self.assertEqual(booking[0]['href'], 'https://clinicia.com/calendar/book?u=48267')
        css = (ROOT / 'assets/css/shader-sections.css').read_text()
        self.assertIn('prefers-reduced-motion: reduce', css)
        self.assertTrue((ROOT / 'assets/images/bands-background.webp').is_file())

    def test_philosophy_reuses_the_local_background_with_its_own_canvas(self):
        nodes = self.page.nodes
        marked = [(i, a) for i, (_, a) in enumerate(nodes) if 'data-bands-background' in a]
        self.assertEqual([a['id'] for _, a in marked], ['hero-ambient', 'ethos', 'testimonials', 'care-cta'])
        for index, _ in marked:
            descendants = [(tag, a) for i, (tag, a) in enumerate(nodes) if index in self.page.ancestors[i]]
            self.assertEqual(sum(tag == 'canvas' for tag, _ in descendants), 1)
            self.assertTrue(any(tag == 'img' and a.get('src') == 'assets/images/bands-background.webp' for tag, a in descendants))

    def test_gallery_comparisons_and_expansion_targets(self):
        nodes = self.page.nodes
        gallery = next(i for i, (_, a) in enumerate(nodes) if a.get('id') == 'gallery')
        inside = [(tag, a) for i, (tag, a) in enumerate(nodes) if gallery in self.page.ancestors[i]]
        self.assertEqual(sum(a.get('class') == 'result-gallery-card' for _, a in inside), 3)
        self.assertEqual(sum(tag == 'input' for tag, _ in inside), 3)
        expands = [a for tag, a in inside if tag == 'button']
        self.assertEqual([a['data-dialog'] for a in expands], [f'gallery-detail-{i}' for i in range(1, 4)])
        dialogs = [a for tag, a in nodes if tag == 'dialog' and a.get('class') == 'gallery-dialog']
        self.assertEqual([a['id'] for a in dialogs], [a['data-dialog'] for a in expands])
        self.assertIn('Your goals. Your journey.', self.raw)
        self.assertNotIn('id="consultation"', self.raw)

    def test_local_runtime_and_clean_content(self):
        stylesheets = [a['href'] for t, a in self.page.nodes if t == 'link' and a.get('rel') == 'stylesheet']
        self.assertFalse(any('swiper' in href or '3629d249d5292713' in href for href in stylesheets))
        scripts = [a['src'] for t, a in self.page.nodes if t == 'script']
        self.assertEqual(scripts, ['assets/vendor/gsap.min.js', 'assets/vendor/ScrollTrigger.min.js', 'assets/vendor/lenis.min.js', 'assets/js/scrollbar.js', 'assets/js/contact.js', 'assets/js/blog.js', 'assets/js/main.js', 'assets/js/reels.js', 'assets/js/effects/bands-background.js'])
        for word in ['api.maisonabelane', '__next_f', 'googletagmanager', 'facebook.com', 'Loading blogs', 'Loading galleries', 'Dubai', '+971']:
            self.assertNotIn(word, self.raw)
        self.assertIn('prefers-reduced-motion: reduce', (ROOT / 'assets/css/main.css').read_text())


if __name__ == '__main__':
    unittest.main(verbosity=2)
